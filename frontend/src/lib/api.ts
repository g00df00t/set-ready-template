import { createClient } from "./supabase";
import { withTimeout } from "./timeout";

export { TimeoutError } from "./timeout";

const BASE_URL = process.env.NEXT_PUBLIC_API_URL ?? "http://localhost:8000";

// A brief Supabase hiccup surfaces as a 5xx from our backend and, before this,
// as an empty screen for the producer. Reads are safe to repeat, so retry them
// rather than making a shoot-day user think their data is gone. Writes are
// never retried — a repeated POST could create a second crew member.
const GET_RETRIES = 2;
const RETRY_BACKOFF_MS = 300;

// A request cut off mid-flight — most often a Railway restart during a deploy —
// can leave fetch waiting forever, and the button that started it stuck on
// "Deleting…". Past this, give up and let the caller's error path run.
export const DEFAULT_TIMEOUT_MS = 30_000;
// Model calls (paste imports, reading a PDF, receipt or estimate) and sending
// mail legitimately take longer. Passed explicitly at those call sites.
export const SLOW_TIMEOUT_MS = 180_000;
const DOWNLOAD_TIMEOUT_MS = 120_000;

class ApiError extends Error {
  status: number;
  constructor(message: string, status: number) {
    super(message);
    this.name = "ApiError";
    this.status = status;
  }
}

async function getAuthHeader(): Promise<Record<string, string>> {
  const supabase = createClient();
  const { data: { session } } = await supabase.auth.getSession();
  const token = session?.access_token;
  return token ? { Authorization: `Bearer ${token}` } : {};
}

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

async function attempt<T>(path: string, options: RequestInit, timeoutMs: number): Promise<T> {
  const authHeader = await getAuthHeader();
  // FormData must set its own Content-Type — the multipart boundary is
  // generated by the browser, and naming the type here strips it, so the
  // server sees a body it can't parse.
  const isFormData = options.body instanceof FormData;
  const write = (options.method ?? "GET") !== "GET";
  // The body is read inside the timeout too — a connection can drop after
  // the headers arrive, and res.json() would wait on it just as long.
  return withTimeout(timeoutMs, options.signal, write, async (signal) => {
    const res = await fetch(`${BASE_URL}${path}`, {
      ...options,
      signal,
      headers: {
        ...(isFormData ? {} : { "Content-Type": "application/json" }),
        ...authHeader,
        ...options.headers,
      },
    });
    if (!res.ok) {
      const error = await res.json().catch(() => ({ detail: res.statusText }));
      const detail = error.detail;
      const message = typeof detail === "string" ? detail : detail ? JSON.stringify(detail) : "Request failed";
      if (res.status === 403 && message === NOT_OWNER_DETAIL) await signOutNotOwner();
      throw new ApiError(message, res.status);
    }
    return res.json();
  });
}

// A producer's own copy turns away every account but its owner's with this
// exact 403 (backend auth.NOT_OWNER_DETAIL). Supabase itself still signs such
// an account in — that's client-side — so without this the person lands on a
// dashboard where every call fails and the page says "check your connection",
// which is the wrong story. Sign them out and let the login page say why.
export const NOT_OWNER_DETAIL = "This Set Ready belongs to someone else.";
let signingOut = false;

async function signOutNotOwner() {
  if (signingOut || typeof window === "undefined") return;
  signingOut = true;
  try { await createClient().auth.signOut(); } catch { /* the redirect is what matters */ }
  window.location.assign("/auth/login?error=not-owner");
}

async function request<T>(
  path: string, options: RequestInit = {}, retries = 0, timeoutMs = DEFAULT_TIMEOUT_MS,
): Promise<T> {
  for (let i = 0; ; i++) {
    try {
      return await attempt<T>(path, options, timeoutMs);
    } catch (err) {
      // A 4xx is a real answer — the caller asked for something that isn't
      // there, or isn't theirs. Only a 5xx, a dropped connection or a timeout
      // is worth repeating (and only for reads — writes pass retries = 0).
      // An aborted request was cancelled on purpose.
      // Checked by name, not instanceof — an abort surfaces as a DOMException,
      // which isn't reliably an Error subclass across browsers.
      const aborted = options.signal?.aborted || (err as { name?: string } | null)?.name === "AbortError";
      const retriable = !aborted && (!(err instanceof ApiError) || err.status >= 500);
      if (i >= retries || !retriable) throw err;
      await sleep(RETRY_BACKOFF_MS * (i + 1));
    }
  }
}

/** Fetch a binary file plus the filename the server chose.
 *
 * Separate from `request` because that parses JSON. Reading Content-Disposition
 * cross-origin also depends on the API naming it in expose_headers — without
 * that the browser hides it and every download lands as "download". */
export async function downloadFile(path: string): Promise<{ blob: Blob; filename: string | null }> {
  const authHeader = await getAuthHeader();
  return withTimeout(DOWNLOAD_TIMEOUT_MS, null, false, async (signal) => {
    const res = await fetch(`${BASE_URL}${path}`, { headers: { ...authHeader }, signal });
    if (!res.ok) {
      const error = await res.json().catch(() => ({ detail: res.statusText }));
      const detail = error.detail;
      throw new ApiError(typeof detail === "string" ? detail : "Download failed", res.status);
    }
    const disposition = res.headers.get("Content-Disposition") ?? "";
    const match = /filename\*=UTF-8''([^;]+)|filename="([^"]+)"/i.exec(disposition);
    let filename: string | null = null;
    if (match) {
      try {
        filename = decodeURIComponent(match[1] ?? match[2]);
      } catch {
        filename = match[2] ?? null;
      }
    }
    return { blob: await res.blob(), filename };
  });
}

type PostOptions = { signal?: AbortSignal; timeoutMs?: number };

export const api = {
  get: <T>(path: string) => request<T>(path, {}, GET_RETRIES),
  post: <T>(path: string, body: unknown, opts: PostOptions = {}) =>
    request<T>(path, { method: "POST", body: JSON.stringify(body), signal: opts.signal }, 0, opts.timeoutMs),
  put: <T>(path: string, body: unknown) =>
    request<T>(path, { method: "PUT", body: JSON.stringify(body) }),
  // Uploads carry a file — a big body on a slow connection takes a while, and
  // the raw-body routes below are all model reads — hence the long limit.
  upload: <T>(path: string, form: FormData) =>
    request<T>(path, { method: "POST", body: form }, 0, SLOW_TIMEOUT_MS),
  /** POST a file as the raw request body, typed by `contentType` — for routes
   * that stream and cap the body themselves rather than parse a form. */
  uploadFile: <T>(path: string, file: Blob, contentType: string) =>
    request<T>(path, { method: "POST", body: file, headers: { "Content-Type": contentType } }, 0, SLOW_TIMEOUT_MS),
  delete: <T>(path: string) => request<T>(path, { method: "DELETE" }),
};
